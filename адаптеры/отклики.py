"""Отклики: ответы на вопрос ритуала, записанные кликом по кнопке.

Ритуал спрашивает про свежее событие «как это на тебя повлияло» и даёт четыре
кнопки по числу лучей. Кнопка это ссылка на `/отклик`, её принимает `поле.py` и
дописывает строку в `источники/отклики.json`. Этот адаптер кладёт такие строки
обратно на крест.

Остальные адаптеры говорят, что с тобой происходит. Этот говорит, что ты сам об
этом думаешь, и потому весит больше: рука важнее счётчика. Отклик на луче
ресурсов держит, на остальных тянет.

Настройка через окружение:
    KREST_ОТКЛИКИ  путь к файлу, по умолчанию источники/отклики.json
"""
import os, json, pathlib, datetime as dt

ФАЙЛ = pathlib.Path(os.environ.get("KREST_ОТКЛИКИ", "")).expanduser() if os.environ.get("KREST_ОТКЛИКИ") \
    else pathlib.Path(__file__).parent.parent / "источники" / "отклики.json"
ЛУЧИ = {"обязательства", "будущее", "ресурсы", "прошлое"}


def _часы(строка, сейчас):
    """Сколько часов прошло с отклика. Отрицательное: отклик всегда позади."""
    try:
        t = dt.datetime.fromisoformat(str(строка))
    except (TypeError, ValueError):
        return -0.1
    if t.tzinfo is None:
        t = t.replace(tzinfo=сейчас.tzinfo)
    return -max(0.1, (сейчас - t).total_seconds() / 3600)


def собрать(правила, сейчас):
    п = правила["источники"].get("отклики")
    if п is None:
        return {"статус": "off", "элементы": [], "события": [],
                "заметка": "источник отклики не описан в правила.json"}
    if not ФАЙЛ.exists():
        return {"статус": "quiet", "элементы": [], "события": [],
                "заметка": "откликов пока нет, они появятся после первого клика"}
    try:
        строки = json.loads(ФАЙЛ.read_text(encoding="utf-8"))
        if not isinstance(строки, list):
            raise ValueError("ожидался список")
    except Exception as ex:
        return {"статус": "dead", "элементы": [], "события": [],
                "заметка": f"{type(ex).__name__}: {str(ex)[:60]}"}

    элементы = []
    for i, о in enumerate(строки):
        луч = о.get("луч")
        if луч not in ЛУЧИ:
            continue                                   # чужой луч, строка пропускается
        подпись = о.get("текст") or о.get("событие") or "отклик"
        элементы.append({
            "id": f"отклик-{i}",
            "т": f"сказано рукой: {подпись}",
            "луч": луч,
            "вес": round(float(п.get("база", 2.0)), 2),
            "т_ч": round(_часы(о.get("время"), сейчас), 1),
            "охват": п["охват"],
            "источник": "отклики",
            "знак": "+" if луч == "ресурсы" else "",
            "факт": f"ответ на вопрос ритуала, {str(о.get('время', ''))[:16]}",
            "флип": п["флип"],
            "природа": "держит" if луч == "ресурсы" else "тянет",
        })

    return {"статус": "live" if элементы else "quiet", "элементы": элементы, "события": [],
            "заметка": f"откликов {len(элементы)}"}
