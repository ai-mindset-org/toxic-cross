"""Пустой адаптер. Скопируй файл, переименуй, впиши своё чтение.

Дальше добавь имя файла (без .py) в список АДАПТЕРЫ в собрать.py и опиши
источник в правила.json: луч, охват, масштаб, правила, флип.

Пять правил приличия, проверенных на живых источниках:

1. Падать тихо. Источник недоступен – верни статус dead с короткой заметкой.
   Поле нарисует остальные лучи и покрасит этот источник красным.
2. Не ходить дважды. Дорогой источник читается по снимку на диске, а не при
   каждой сборке. Решает адаптер, а не расписание.
3. Сворачивать хвост. Поимённо приходит только горящее. Остальное сложи в один
   блок со счётчиком, иначе луч превратится в список.
4. Отдавать факт и флип. Факт объясняет вес числом, флип говорит, что с этим
   можно сделать. Без них блок молчит.
5. Только чтение. Инструменту не нужны права на запись ни к одному источнику.
"""
import datetime as dt


def собрать(правила, сейчас):
    """Вернуть элементы одного источника.

    правила – разобранный правила.json, свой раздел лежит в
              правила["источники"]["<имя источника>"]
    сейчас   – datetime с поясом, точка отсчёта времени

    Возврат:
        статус   – live (данные есть) · quiet (пусто, это норма) ·
                   dead (источник недоступен) · off (выключен)
        элементы – список блоков, поля описаны ниже
        события  – список для ленты дня, можно пустой
        заметка  – одна строка для строки источников на поле
    """
    п = правила["источники"].get("образец")
    if п is None:
        return {"статус": "off", "элементы": [], "события": [],
                "заметка": "источник не описан в правила.json"}

    элементы = [{
        "id": "обр-1",                      # устойчивый между сборками
        "т": "короткая подпись блока",      # то, что видно на луче
        "луч": п["луч"],                    # обязательства · прошлое · ресурсы · будущее
        "вес": 2.0,                         # база до масштаба и затухания
        "т_ч": 6,                           # часы от сейчас: вперёд плюс, назад минус
        "охват": п["охват"],                # ситуативное · недельное · глобальное
        "источник": "образец",              # ключ в правила.json["источники"]
        "факт": "чем этот вес обоснован: число, срок, счётчик",
        "флип": п["флип"],                  # что с этим можно сделать
        "природа": "тянет",                 # тянет вверх · держит внизу
    }]
    return {"статус": "live", "элементы": элементы, "события": [],
            "заметка": f"элементов {len(элементы)}"}
