"""Календарь из файла ICS.

Берёт локальный .ics (выгрузка из любого календаря) или адрес подписки, оставляет
события сегодняшнего дня и складывает из них два луча: встречи идут в обязательства,
свободные часы дня идут в ресурсы.

Настройка через окружение:
    KREST_ICS   путь к файлу или https-адрес подписки
    KREST_MAIL  своя почта, чтобы не считать себя участником

Без настройки адаптер берёт `источники/образец.ics` и переносит его события на
сегодня, чтобы поле было полным сразу после клонирования. Статус в этом случае
`образец`, а не `live`: на экране выдуманный день.

Прав нужно ровно одно: чтение. Инструмент ничего не переносит и не создаёт.
"""
import os, re, pathlib, datetime as dt, urllib.request

ICS = os.environ.get("KREST_ICS", "")
МОЙ = os.environ.get("KREST_MAIL", "")
ОБРАЗЕЦ = pathlib.Path(__file__).parent.parent / "источники" / "образец.ics"


def _на_сегодня(текст, день):
    """Переносит даты образца на сегодня: у выдуманного дня своей даты быть не должно."""
    return re.sub(r"^(DTSTART|DTEND):\d{8}", lambda m: f"{m.group(1)}:{день:%Y%m%d}",
                  текст, flags=re.M)


def _текст(день=None):
    """Файл читается с диска, адрес скачивается. Без настройки берётся образец."""
    if not ICS:
        if ОБРАЗЕЦ.exists() and день is not None:
            return _на_сегодня(ОБРАЗЕЦ.read_text(encoding="utf-8"), день)
        return ""
    if ICS.startswith(("http://", "https://")):
        with urllib.request.urlopen(ICS, timeout=30) as r:
            return r.read().decode("utf-8", "replace")
    return pathlib.Path(ICS).expanduser().read_text(encoding="utf-8", errors="replace")


def _события(текст, день):
    """Простейший разбор VEVENT: начало, конец, заголовок, число участников."""
    события = []
    for кусок in текст.split("BEGIN:VEVENT")[1:]:
        поля = dict(re.findall(r"^(DTSTART|DTEND|SUMMARY)[^:\n]*:(.+)$", кусок, re.M))
        начало = поля.get("DTSTART", "").strip()
        if not начало.startswith(день.strftime("%Y%m%d")):
            continue                                   # чужой день
        try:
            t0 = dt.datetime.strptime(начало[:15], "%Y%m%dT%H%M%S")
            t1 = dt.datetime.strptime(поля.get("DTEND", начало)[:15], "%Y%m%dT%H%M%S")
        except ValueError:
            continue                                   # событие на весь день
        гости = [a for a in re.findall(r"ATTENDEE[^\n]*mailto:([^\s;]+)", кусок) if a != МОЙ]
        события.append({"т": поля.get("SUMMARY", "встреча").strip(), "t0": t0,
                        "мин": max(1, int((t1 - t0).total_seconds() / 60)), "гости": len(гости)})
    return события


def собрать(правила, сейчас):
    п = правила["источники"]["календарь"]
    образец = not ICS
    if образец and not ОБРАЗЕЦ.exists():
        return {"статус": "off", "элементы": [], "события": [], "заметка": "KREST_ICS не задан"}
    try:
        события = _события(_текст(сейчас.date()), сейчас.date())
    except Exception as ex:
        return {"статус": "dead", "элементы": [], "события": [],
                "заметка": f"{type(ex).__name__}: {str(ex)[:60]}"}

    элементы, лента, занято = [], [], 0
    for i, с in enumerate(события):
        занято += с["мин"]
        вес = min(3.0, 1 + 0.5 * с["гости"]) * (1.5 if с["мин"] > 90 else 1.0)
        часы = (с["t0"].replace(tzinfo=сейчас.tzinfo) - сейчас).total_seconds() / 3600
        элементы.append({
            "id": f"cal-{сейчас:%Y%m%d}-{i}", "т": с["т"], "луч": п["луч"], "вес": round(вес, 2),
            "т_ч": round(часы, 1), "охват": п["охват"], "источник": "календарь",
            "факт": f"{с['t0']:%H:%M}, {с['мин']} мин, участников кроме меня {с['гости']}",
            "флип": п["флип"], "природа": "тянет",
        })
        лента.append({"t": с["t0"].isoformat(timespec="minutes"), "т": с["т"], "источник": "календарь"})

    # свободные часы рабочего дня уходят опорой на нижний луч, ноль часов становится дефицитом
    свободно = round(max(0.0, 10 - занято / 60), 1)
    элементы.append({
        "id": "cal-свободно", "т": f"свободных часов сегодня: {свободно}", "луч": "ресурсы",
        "вес": round(0.5 * свободно, 2) if свободно else -2.0, "т_ч": 8, "охват": "ситуативное",
        "источник": "календарь", "факт": f"окно 09–19 минус встречи, занято {занято} мин",
        "флип": "два свободных часа это одна задача целиком",
        "природа": "держит" if свободно else "тянет",
    })

    заметка = f"событий {len(события)}, занято {занято} мин"
    if образец:
        заметка += " · выдуманный день, задай KREST_ICS для своего"
    статус = "образец" if образец else ("live" if события else "quiet")
    return {"статус": статус, "элементы": элементы, "события": лента, "заметка": заметка}
