"""Задачи из файла JSON.

Читает выгрузку трекера: список задач со статусом, приоритетом, сроком и датой
последнего движения. Открытые задачи идут в обязательства, закрытые за месяц
складываются одним блоком в прошлое и работают опорой.

Настройка через окружение:
    KREST_ЗАДАЧИ  путь к файлу, по умолчанию источники/задачи.json

Формат входа: либо голый список задач, либо объект с ключом "задачи".
    {"ключ": "142", "название": "отчёт по гранту", "статус": "в работе",
     "приоритет": 1, "срок": "2026-09-22T18:00", "движение": "2026-09-09"}

У встроенного образца есть ключ "_база": все его даты сдвигаются так, чтобы
день выглядел сегодняшним. У своей выгрузки этого ключа нет и даты берутся как есть.
"""
import os, json, pathlib, datetime as dt

def _файл():
    """Своя выгрузка ищется раньше образца: задачи.local.json уже в .gitignore."""
    если_задан = os.environ.get("KREST_ЗАДАЧИ")
    if если_задан:
        return pathlib.Path(если_задан).expanduser()
    папка = pathlib.Path(__file__).parent.parent / "источники"
    свой = папка / "задачи.local.json"
    return свой if свой.exists() else папка / "задачи.json"


ФАЙЛ = _файл()


def _часы(строка, сейчас):
    """Часы от сейчас до даты. Пустая дата даёт горизонт месяца."""
    if not строка:
        return 720
    try:
        t = dt.datetime.fromisoformat(str(строка).replace("Z", "+00:00"))
    except ValueError:
        return 720
    if t.tzinfo is None:
        t = t.replace(tzinfo=сейчас.tzinfo)
    return (t - сейчас).total_seconds() / 3600


def _дней(строка, сейчас):
    try:
        t = dt.datetime.fromisoformat(str(строка))
    except (TypeError, ValueError):
        return 0
    if t.tzinfo is None:
        t = t.replace(tzinfo=сейчас.tzinfo)
    return max(0.0, (сейчас - t).total_seconds() / 86400)


def собрать(правила, сейчас):
    п = правила["источники"]["задачи"]
    if not ФАЙЛ.exists():
        return {"статус": "quiet", "элементы": [], "события": [],
                "заметка": f"нет файла {ФАЙЛ.name}"}
    try:
        сырое = json.loads(ФАЙЛ.read_text(encoding="utf-8"))
        задачи = сырое["задачи"] if isinstance(сырое, dict) else сырое
        база = сырое.get("_база") if isinstance(сырое, dict) else None
        if база:                                        # образец: перенести на сегодня
            сдвиг = сейчас.date() - dt.date.fromisoformat(база)
            задачи = [dict(з, **{к: (dt.datetime.fromisoformat(з[к]) + сдвиг).isoformat()
                                 for к in ("срок", "движение") if з.get(к)}) for з in задачи]
    except Exception as ex:
        return {"статус": "dead", "элементы": [], "события": [],
                "заметка": f"{type(ex).__name__}: {str(ex)[:60]}"}

    элементы, закрытых = [], 0
    for з in задачи:
        статус = str(з.get("статус", "")).lower()
        if статус in ("закрыто", "done", "closed"):
            if _дней(з.get("срок"), сейчас) <= 30:
                закрытых += 1
            continue

        часы = _часы(з.get("срок"), сейчас)
        просрочено = часы < 0
        вес = max(0.5, 4 - int(з.get("приоритет", 2)))
        if _дней(з.get("движение"), сейчас) > 30:
            вес *= 1.5                                  # лежит без движения
        if просрочено:
            вес *= 1.4                                  # срок уже прошёл

        элементы.append({
            "id": f"задача-{з.get('ключ', len(элементы))}",
            "т": з.get("название", "задача") + (": просрочено" if просрочено else ""),
            "луч": п["луч"], "вес": round(вес, 2), "т_ч": round(часы, 1),
            "срочно": просрочено,                       # просроченное садится в центр
            "охват": п["охват"], "источник": "задачи",
            "факт": ("срок прошёл" if просрочено else f"до срока {round(часы)} ч")
                    + f", приоритет {з.get('приоритет', '—')}",
            "флип": п["флип"], "природа": "тянет",
        })

    if закрытых:
        элементы.append({
            "id": "задачи-закрыто30", "т": f"закрыто за месяц: {закрытых}", "луч": "прошлое",
            "вес": round(min(4.0, 0.4 * закрытых), 2), "т_ч": -360, "охват": "глобальное",
            "источник": "задачи", "знак": "+",
            "факт": f"{закрытых} задач со статусом закрыто за 30 дней",
            "флип": "этот темп уже был, он воспроизводим", "природа": "держит",
        })

    return {"статус": "live" if элементы else "quiet", "элементы": элементы, "события": [],
            "заметка": f"открытых {len([e for e in элементы if e['луч'] == п['луч']])}, закрытых за месяц {закрытых}"}
